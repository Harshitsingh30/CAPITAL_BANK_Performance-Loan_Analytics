# TRANSACTION SACTION
-- TOTAL COUNT OF TRANSACTIONS BY TRANSACTIONS_TYPE
SELECT TYPE, COUNT(TRANSACTIONID) AS TOTAL_TRANSACTION FROM TRANSACTIONS_TYPE
INNER JOIN TRANSACTIONS
ON TRANSACTIONS_TYPE.TRANSACTIONTYPEID=TRANSACTIONS.TRANSACTIONTYPEID
GROUP BY TYPE
ORDER BY TOTAL_TRANSACTION DESC;

-- SUM OF AMOUNT BY TRANSACTION_TYPE
SELECT TYPE AS TRANSACTION_TYPE,ROUND(SUM(AMOUNT),2) AS TOTAL_AMOUNT FROM TRANSACTIONS_TYPE
INNER JOIN TRANSACTIONS
ON TRANSACTIONS_TYPE.TRANSACTIONTYPEID=TRANSACTIONS.TRANSACTIONTYPEID
GROUP BY TRANSACTION_TYPE
ORDER BY TOTAL_AMOUNT DESC;

-- TOTAL COUNT OF TRANSATIONS BY BRANCH
SELECT BRANCH,COUNT(TRANSACTIONID) AS TOTAL_TRANSACTIONS FROM BRANCHES
INNER JOIN TRANSACTIONS
ON TRANSACTIONS.BRANCHID=BRANCHES.BRANCHID
GROUP BY BRANCH
ORDER BY TOTAL_TRANSACTIONS DESC;

-- ANALYSIS OF TRANSACTION_TYPE BY BRANCH
SELECT BRANCH,TYPE,COUNT(TRANSACTIONID) AS TOTAL_TRANSACTIONS FROM BRANCHES
INNER JOIN TRANSACTIONS
ON TRANSACTIONS.BRANCHID=BRANCHES.BRANCHID
INNER JOIN TRANSACTIONS_TYPE
ON TRANSACTIONS_TYPE.TRANSACTIONTYPEID=TRANSACTIONS.TRANSACTIONTYPEID
GROUP BY BRANCH,TYPE
ORDER BY BRANCH,TOTAL_TRANSACTIONS DESC;

-- TOTAL TRANSACTIONS BY YEAR
SELECT YEAR(TRANSACTIONDATE) AS YEAR,COUNT(TRANSACTIONID) AS TOTAL_TRANSACTIONS FROM TRANSACTIONS
GROUP BY YEAR
ORDER BY YEAR(TRANSACTIONDATE);

-- TOTAL TRANSACTIONS BY MONTH
SELECT MONTHNAME(TRANSACTIONDATE) AS MONTH_NAME, COUNT(TRANSACTIONID) AS TOTAL_TRANSACTIONS FROM TRANSACTIONS
GROUP BY MONTH(TRANSACTIONDATE), MONTH_NAME
ORDER BY MONTH(TRANSACTIONDATE);

-- RANK TOP 5 BRANCHES ON THE BASIS OF TRANSACTION COUNT
SELECT B.BRANCHID,B.BRANCH,COUNT(T.TRANSACTIONID) AS TRANSACTION_COUNT,
ROW_NUMBER() OVER(ORDER BY COUNT(T.TRANSACTIONID)DESC) AS BRANCH_RANK  FROM BRANCHES B
INNER JOIN TRANSACTIONS T
ON B.BRANCHID=T.BRANCHID
GROUP BY B.BRANCHID,B.BRANCH
ORDER BY BRANCH_RANK
LIMIT 5;

