# ACCOUNT SECTION
-- TOTAL ACCOUNT 
SELECT COUNT(ACCOUNTID) AS TOTAL_ACCOUNT FROM ACCOUNT;

-- SUM OF TOTAL BALANCE IN BANK
SELECT ROUND(SUM(BALANCE),0) AS TOTAL_BALANCE FROM ACCOUNT; 

-- TOTAL ACCOUNT BY ACCOUNT_STATUS
SELECT STATUS,COUNT(ACCOUNTID) AS TOTAL_ACCOUNT FROM ACCOUNT
INNER JOIN ACCOUNT_STATUS
ON ACCOUNT.ACCOUNTSTATUSID=ACCOUNT_STATUS.ACCOUNTSTATUSID
GROUP BY STATUS
ORDER BY TOTAL_ACCOUNT DESC;

-- TOTAL ACCOUNT BY ACCOUNT_TYPE
SELECT TYPE,COUNT(ACCOUNTID) AS TOTAL_ACCOUNT FROM ACCOUNT_TYPE
INNER JOIN ACCOUNT
ON ACCOUNT_TYPE.ACCOUNTTYPEID=ACCOUNT.ACCOUNTTYPEID
GROUP BY TYPE
ORDER BY TOTAL_ACCOUNT DESC;

-- TOTAL ACCOUNT BASED ON CITY
SELECT CITY,COUNT(ACCOUNTID) AS TOTAL_ACCOUNT FROM ADDRESS
INNER JOIN CUSTOMERS
ON ADDRESS.ADDRESSID=CUSTOMERS.ADDRESSID
INNER JOIN ACCOUNT
ON CUSTOMERS.CUSTOMERID=ACCOUNT.CUSTOMERID
GROUP BY CITY
ORDER BY TOTAL_ACCOUNT DESC;

-- AVERAGE BALANCE BY ACCOUNT_TYPE
SELECT TYPE, ROUND(AVG(BALANCE),0) AS AVERAGE_BALANCE FROM ACCOUNT
INNER JOIN ACCOUNT_TYPE
ON ACCOUNT.ACCOUNTTYPEID=ACCOUNT_TYPE.ACCOUNTTYPEID
GROUP BY TYPE
ORDER BY AVERAGE_BALANCE DESC;

-- SUM OF TOTAL BALANCE BY ACCOUNT_STATUS
SELECT STATUS,ROUND(SUM(BALANCE),0) AS TOTAL_BALANCE FROM ACCOUNT_STATUS
INNER JOIN ACCOUNT
ON ACCOUNT_STATUS.ACCOUNTSTATUSID=ACCOUNT.ACCOUNTSTATUSID
GROUP BY STATUS
ORDER BY TOTAL_BALANCE DESC;

-- TOTAL ACCOUNT BY CUSTOMER_TYPE
SELECT TYPE,COUNT(ACCOUNTID) AS TOTAL_ACCOUNT FROM CUSTOMER_TYPE
INNER JOIN CUSTOMERS
ON CUSTOMER_TYPE.CUSTOMERTYPEID=CUSTOMERS.CUSTOMERTYPEID
INNER JOIN ACCOUNT
ON CUSTOMERS.CUSTOMERID=ACCOUNT.CUSTOMERID
GROUP BY TYPE
ORDER BY TOTAL_ACCOUNT DESC;

-- ACCOUNT OPENING COUNT BY MONTH
SELECT MONTHNAME(OPENINGDATE) AS MONTH_NAME, COUNT(ACCOUNTID) AS TOTAL_ACCOUNT_OPEN FROM ACCOUNT
GROUP BY MONTH(OPENINGDATE),MONTH_NAME
ORDER BY MONTH(OPENINGDATE);

-- ACCOUNT OPENING COUNT BY YEAR
SELECT YEAR(OPENINGDATE) AS YEAR, COUNT(ACCOUNTID) AS TOTAL_ACCOUNT_OPEN FROM ACCOUNT
GROUP BY YEAR(OPENINGDATE)
ORDER BY YEAR;


# LOAN SECTION
